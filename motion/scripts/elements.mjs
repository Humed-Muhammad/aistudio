// Lists every library graphic (src/elements/pack and src/elements/mine: name.json + name.tsx) in
// src/elements/registry.gen.ts, which the renderer and the studio import. Run before building or rendering:
//   node scripts/elements.mjs        (studio:build and shorts.py do this for you)
// Prints problems (missing .tsx, id not matching the file name, duplicates) and skips those graphics.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "elements");
const imports = [];
const rows = [];
const seen = new Set();
let n = 0;
for (const source of ["pack", "mine"]) {
  const dir = path.join(root, source);
  if (!fs.existsSync(dir)) continue;
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
    const id = file.slice(0, -5);
    let meta;
    try {
      meta = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"));
    } catch (e) {
      console.warn(`skipped ${source}/${file}: not valid JSON (${e.message})`);
      continue;
    }
    if (!fs.existsSync(path.join(dir, `${id}.tsx`))) console.warn(`skipped ${source}/${id}: no ${id}.tsx`);
    else if (meta.id !== id) console.warn(`skipped ${source}/${id}: "id" in the JSON must be "${id}"`);
    else if (seen.has(id)) console.warn(`skipped ${source}/${id}: a graphic with this id already exists`);
    else {
      seen.add(id);
      imports.push(`import m${n} from "./${source}/${id}.json";`, `import C${n} from "./${source}/${id}";`);
      rows.push(`  ${JSON.stringify(id)}: { meta: m${n} as ElementMeta, Component: C${n}, source: "${source}" },`);
      n++;
    }
  }
}
const out = [
  "// Generated by scripts/elements.mjs from src/elements/pack and src/elements/mine. Do not edit.",
  'import type { ElementEntry, ElementMeta } from "./types";',
  ...imports,
  "",
  "export const ELEMENTS: Record<string, ElementEntry> = {",
  ...rows,
  "};",
  "",
].join("\n");
const target = path.join(root, "registry.gen.ts");
if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== out) fs.writeFileSync(target, out);
console.log(`${n} graphics in the library`);
