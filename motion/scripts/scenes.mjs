// Lists every film scene template (src/film/scenes/pack and src/film/scenes/mine: name.json + name.tsx) in
// src/film/registry.gen.ts, which the renderer and the studio import, and writes src/film/catalog.gen.json
// (scene fields, icon names) for films.py. Run before building or rendering:
//   node scripts/scenes.mjs        (studio:build and films.py do this for you)
// Prints problems (missing .tsx, id not matching the file name, duplicates) and skips those scenes.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const film = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "film");
const root = path.join(film, "scenes");
const imports = [];
const rows = [];
const catalog = {};
const seen = new Set();
let n = 0;
for (const source of ["pack", "mine"]) {
  const dir = path.join(root, source);
  if (!fs.existsSync(dir)) continue;
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
    const id = file.slice(0, -5);
    let meta;
    try {
      meta = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"));
    } catch (e) {
      console.warn(`skipped ${source}/${file}: not valid JSON (${e.message})`);
      continue;
    }
    if (!fs.existsSync(path.join(dir, `${id}.tsx`))) console.warn(`skipped ${source}/${id}: no ${id}.tsx`);
    else if (meta.id !== id) console.warn(`skipped ${source}/${id}: "id" in the JSON must be "${id}"`);
    else if (seen.has(id)) console.warn(`skipped ${source}/${id}: a scene with this id already exists`);
    else {
      seen.add(id);
      imports.push(`import m${n} from "./scenes/${source}/${id}.json";`, `import * as S${n} from "./scenes/${source}/${id}";`);
      rows.push(`  ${JSON.stringify(id)}: { meta: m${n} as SceneMeta, Component: S${n}.default, cues: (S${n} as SceneModule).cues, source: "${source}" },`);
      catalog[id] = { ...meta, source };
      n++;
    }
  }
}
const out = [
  "// Generated by scripts/scenes.mjs from src/film/scenes/pack and src/film/scenes/mine. Do not edit.",
  'import type { SceneEntry, SceneMeta, SceneModule } from "./types";',
  ...imports,
  "",
  "export const SCENES: Record<string, SceneEntry> = {",
  ...rows,
  "};",
  "",
].join("\n");
const write = (name, text) => {
  const target = path.join(film, name);
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== text) fs.writeFileSync(target, text);
};
write("registry.gen.ts", out);
const iconNames = [...fs.readFileSync(path.join(film, "icons.tsx"), "utf8").split("const ICONS")[1].split("};")[0].matchAll(/(?:"([a-z-]+)"|\b([a-z]+)):\s*[A-Z]/g)].map((m) => m[1] ?? m[2]);
write("catalog.gen.json", JSON.stringify({ scenes: catalog, icons: iconNames }, null, 1) + "\n");
console.log(`${n} film scenes, ${iconNames.length} icons`);
